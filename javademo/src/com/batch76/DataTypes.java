package com.batch76;

public class DataTypes {

	public static void main(String[] args) {
		//Primitive Data Types                                   //Integer
		                                                              // int->4byte->
		                                                              //long->8bytes->
		                                                              // short->2bytes->
		                                                              // byte =>1byte ->
		//Integer
		//byte,short,int,long
		
		int num1 = 9;
		byte by =127;
		short sh = 558;
		long l = 5854l;
		int result = num1+by;
		System.out.println(result);
		
		//Float -> 4byte
		
		float f = 5.8f;
	
		//double ->8bytes
		double d = 5.8;
		
		//Character -> 2byte
		
		char c = 'k';
		
		//Boolean
		boolean b = true;
		

	}

}
